-- ------------------------------------------------------------
-- 1. RLS METADATA CATALOG TABLE
-- ------------------------------------------------------------
CREATE TABLE Z72385.HMS_RLS_POLICIES (
    POLICY_ID     INTEGER        NOT NULL GENERATED ALWAYS AS IDENTITY
                                 (START WITH 1 INCREMENT BY 1),
    POLICY_NAME   VARCHAR(100)   NOT NULL,
    TARGET_TABLE  VARCHAR(100)   NOT NULL,
    TARGET_ROLE   VARCHAR(50)    NOT NULL,
    POLICY_TYPE   VARCHAR(30)    NOT NULL WITH DEFAULT 'ROW_PERM',
    RULE_FILTER   VARCHAR(500)   NOT NULL,
    ENFORCED      CHAR(1)        NOT NULL WITH DEFAULT 'Y',
    STATUS        VARCHAR(20)    NOT NULL WITH DEFAULT 'ACTIVE',
    DESCRIPTION   VARCHAR(500)   NOT NULL,
    CREATED_AT    TIMESTAMP      NOT NULL WITH DEFAULT,
    CONSTRAINT PK_HMS_RLS PRIMARY KEY (POLICY_ID),
    CONSTRAINT UQ_RLS_NAME UNIQUE (POLICY_NAME)
) IN DATABASE Z72385;

-- ------------------------------------------------------------
-- 2. RLS AUDIT & POLICY VIEW
-- ------------------------------------------------------------
CREATE VIEW Z72385.V_RLS_POLICIES AS
SELECT POLICY_ID, POLICY_NAME, TARGET_TABLE, TARGET_ROLE,
       POLICY_TYPE, RULE_FILTER, ENFORCED, STATUS, DESCRIPTION,
       CHAR(CREATED_AT) AS CREATED_AT
FROM Z72385.HMS_RLS_POLICIES;

-- ------------------------------------------------------------
-- 3. DOCTOR TREATED PATIENTS SECURE VIEW (RLS SCOPED)
-- ------------------------------------------------------------
CREATE VIEW Z72385.V_DOC_TREATED_PATIENTS AS
SELECT DISTINCT
    A.DOCTOR_ID,
    P.PATIENT_ID,
    P.PAT_NAME,
    P.PAT_AGE,
    P.PAT_GENDER,
    P.PAT_CONTACT,
    P.PAT_EMAIL,
    MAX(A.APPT_DATE) AS LAST_CONSULTATION
FROM Z72385.HMS_PATIENTS P
JOIN Z72385.HMS_APPOINTMENTS A ON P.PATIENT_ID = A.PATIENT_ID
GROUP BY A.DOCTOR_ID, P.PATIENT_ID, P.PAT_NAME, P.PAT_AGE,
         P.PAT_GENDER, P.PAT_CONTACT, P.PAT_EMAIL;

