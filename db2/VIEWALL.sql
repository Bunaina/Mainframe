SELECT CURRENT SERVER AS SERVER, CURRENT SQLID AS SQLID,
       CURRENT TIMESTAMP AS CHECKED_AT
FROM SYSIBM.SYSDUMMY1;

SELECT 'HMS_ADMIN'         AS TABLE_NAME, COUNT(*) AS ROW_CNT
  FROM Z72385.HMS_ADMIN
UNION ALL
SELECT 'HMS_WARDS',         COUNT(*) FROM Z72385.HMS_WARDS
UNION ALL
SELECT 'HMS_DOCTORS',       COUNT(*) FROM Z72385.HMS_DOCTORS
UNION ALL
SELECT 'HMS_PATIENTS',      COUNT(*) FROM Z72385.HMS_PATIENTS
UNION ALL
SELECT 'HMS_STAFF',         COUNT(*) FROM Z72385.HMS_STAFF
UNION ALL
SELECT 'HMS_APPOINTMENTS',  COUNT(*) FROM Z72385.HMS_APPOINTMENTS
UNION ALL
SELECT 'HMS_PRESCRIPTIONS', COUNT(*) FROM Z72385.HMS_PRESCRIPTIONS
UNION ALL
SELECT 'HMS_BILLING',       COUNT(*) FROM Z72385.HMS_BILLING
UNION ALL
SELECT 'HMS_FEEDBACK',      COUNT(*) FROM Z72385.HMS_FEEDBACK;

SELECT ADMIN_ID, ADM_USERNAME
  FROM Z72385.HMS_ADMIN
  ORDER BY ADMIN_ID;

SELECT WARD_ID, WARD_TYPE, TOTAL_BEDS, OCCPD_BEDS
  FROM Z72385.HMS_WARDS
  ORDER BY WARD_ID;

SELECT DOCTOR_ID, SUBSTR(DOC_NAME,1,22) AS DOC_NAME,
       SUBSTR(SPECIALIZ,1,15) AS SPEC,
       SUBSTR(DEPARTMENT,1,12) AS DEPT, DOC_STATUS
  FROM Z72385.HMS_DOCTORS
  ORDER BY DOCTOR_ID;

SELECT PATIENT_ID, SUBSTR(PAT_NAME,1,18) AS PAT_NAME,
       PAT_AGE, PAT_GENDER, SUBSTR(PAT_EMAIL,1,22) AS EMAIL
  FROM Z72385.HMS_PATIENTS
  ORDER BY PATIENT_ID;

SELECT STAFF_ID, SUBSTR(STF_NAME,1,18) AS STF_NAME,
       SUBSTR(STF_ROLE,1,15) AS ROLE, SUBSTR(STF_DEPT,1,12) AS DEPT
  FROM Z72385.HMS_STAFF
  ORDER BY STAFF_ID;

SELECT APPT_ID, PATIENT_ID, DOCTOR_ID,
       APPT_DATE, APPT_TIME, APPT_STATUS
  FROM Z72385.HMS_APPOINTMENTS
  ORDER BY APPT_ID;

SELECT PRESC_ID, APPT_ID, PATIENT_ID, DOCTOR_ID,
       SUBSTR(MEDICINE,1,20) AS MEDICINE,
       SUBSTR(DOSAGE,1,15) AS DOSAGE
  FROM Z72385.HMS_PRESCRIPTIONS
  ORDER BY PRESC_ID;

SELECT BILL_ID, PATIENT_ID, AMOUNT, BILL_STATUS,
       SUBSTR(DESCRIPTION,1,30) AS DESC
  FROM Z72385.HMS_BILLING
  ORDER BY BILL_ID;

SELECT FDBK_ID, PATIENT_ID, FDBK_DATE, FDBK_STATUS,
       SUBSTR(FDBK_MESSAGE,1,35) AS MESSAGE
  FROM Z72385.HMS_FEEDBACK
  ORDER BY FDBK_ID;

